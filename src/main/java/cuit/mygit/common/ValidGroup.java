package cuit.mygit.common;

/**
 * 参数校验的"分组"标记。
 * <p>
 * <b>为什么需要它？</b>因为"新增"和"修改"对同一个字段的要求是不一样的。
 * 举两个例子：
 * <ul>
 *   <li>文章ID：新增的时候还没有ID（数据库自增生成），要求它必填是没道理的；
 *       但修改时没ID就不知道该改哪一篇，必须必填。</li>
 *   <li>用户密码：注册时必须填；修改资料时不填表示"不改密码"，
 *       这时候要是强制必填，用户每次改个邮箱都得重新输一遍密码。</li>
 * </ul>
 * <p>
 * 注解里可以写 {@code groups = ValidGroup.Create.class}，表示"这条规则
 * 只在新增时检查"；Controller 那边则用
 * {@code @Validated(ValidGroup.Create.class)} 声明"这次请求按新增的规则来"。
 * 两边一配合，同一个实体类就能同时应付两种场景，不用写两个几乎一样的类。
 * <p>
 * <b>注意</b>：这两个接口是空的，永远不会有实现类。它们不承载任何逻辑，
 * 只是给注解当"标签"用 —— 相当于给校验规则分了个类，让 Spring 知道
 * 某条规则该在什么时候生效。
 * <p>
 * 没写 groups 的注解属于 {@code Default} 分组，<b>任何分组下都不会被检查</b>，
 * 所以实体类上每条校验注解都得明确写上 groups。
 */
public interface ValidGroup {

    /**
     * 新增（POST）时用的分组。
     * <p>
     * 划分标准是"提交完整数据"—— 所有必填字段都得给全。
     */
    interface Create {
    }

    /**
     * 修改（PUT）时用的分组。
     * <p>
     * 和新增的区别：主键ID在这里是必填的（要知道改哪一条），
     * 而"不改就保留原值"的那些字段在这里不做必填检查。
     */
    interface Update {
    }
}
